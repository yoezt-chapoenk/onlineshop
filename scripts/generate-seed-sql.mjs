// Generates supabase/_seed.sql from src/lib/products.ts.
// Used once at scaffold time; safe to re-run after editing the seed file.
// Run with: npx tsx scripts/generate-seed-sql.mjs
import { fileURLToPath } from "url";
import { dirname, resolve } from "path";
import { writeFileSync } from "fs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const { products, categories } = await import(
  resolve(__dirname, "../src/lib/products.ts")
);

function sqlString(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}
function sqlBool(v) {
  return v ? "true" : "false";
}
function sqlArray(arr) {
  if (!arr || arr.length === 0) return "'{}'";
  const inner = arr.map((s) => `"${s.replace(/"/g, '\\"')}"`).join(",");
  return `'{${inner}}'`;
}
function sqlJson(obj) {
  return `'${JSON.stringify(obj).replace(/'/g, "''")}'::jsonb`;
}

const lines = [];
lines.push("-- AUTO-GENERATED by scripts/generate-seed-sql.mjs");
lines.push("-- Re-run with: node scripts/generate-seed-sql.mjs");
lines.push("");
lines.push("-- Categories");
for (const c of categories) {
  lines.push(
    `insert into public.categories (slug, name, description, sort_order) values (${sqlString(c.slug)}, ${sqlString(c.name)}, ${sqlString(c.description)}, ${categories.indexOf(c) + 1}) on conflict (slug) do update set name = excluded.name, description = excluded.description, sort_order = excluded.sort_order;`,
  );
}

lines.push("");
lines.push("-- Products");
for (const p of products) {
  lines.push(
    [
      "insert into public.products (",
      "  id, slug, sku, name, short_description, description,",
      "  category_slug, category_label, gender, style, frame,",
      "  retail_price, promotional_price, reseller_price,",
      "  min_wholesale_qty, stock, weight_gram,",
      "  is_featured, is_best_seller, is_new_arrival,",
      "  rating, review_count, colors, frame_color, lens_color, specs",
      ") values (",
      `  gen_random_uuid(), ${sqlString(p.slug)}, ${sqlString(p.sku)}, ${sqlString(p.name)}, ${sqlString(p.shortDescription)}, ${sqlString(p.description)},`,
      `  ${sqlString(p.category)}, ${sqlString(p.categoryLabel)}, ${sqlString(p.gender)}, ${sqlString(p.style)}, ${sqlString(p.frame)},`,
      `  ${p.retailPrice}, ${p.promotionalPrice ?? "null"}, ${p.resellerPrice ?? "null"},`,
      `  ${p.minWholesaleQty}, ${p.stock}, ${p.weightGram},`,
      `  ${sqlBool(p.isFeatured)}, ${sqlBool(p.isBestSeller)}, ${sqlBool(p.isNewArrival)},`,
      `  ${p.rating}, ${p.reviewCount}, ${sqlArray(p.colors)}, ${sqlString(p.frameColor)}, ${p.lensColor ? sqlString(p.lensColor) : "null"}, ${sqlJson(p.specs)}`,
      ") on conflict (slug) do nothing;",
    ].join("\n"),
  );
  for (const t of p.priceTiers) {
    lines.push(
      `insert into public.product_price_tiers (product_id, min_qty, max_qty, unit_price, label) select id, ${t.minQty}, ${t.maxQty ?? "null"}, ${t.unitPrice}, ${sqlString(t.label)} from public.products where slug = ${sqlString(p.slug)} on conflict do nothing;`,
    );
  }
}

writeFileSync(resolve(__dirname, "../supabase/_seed.sql"), lines.join("\n") + "\n");
console.log(`Wrote ${lines.length} lines to supabase/_seed.sql`);
